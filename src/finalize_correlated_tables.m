function results = finalize_correlated_tables(cfg,cases,outputDir)
% Recalculate tables from saved paired endpoints, without rerunning SA.
tag='CVaR_correlated_k0_2_R100_corrected';
results=struct('cfg',cfg,'cases',cases,'repairs',{{}});
payload=struct();
settingNames={'noiseModel','k0','phi','CIalpha','CIscale','xunhuancishu', ...
    'N1','Nvalues','theta0','v0','cv0','cu0','Gv0','Gcv0', ...
    'alpha','beta','gamma','gammau','varphi','eta','varsigma', ...
    'alphanc','betanc','gammanc','gammaunc','varphinc','etanc','cnc', ...
    'omega','betah','alphah','hn0','LB','UB','baseSeed'};
settings=repmat(struct('name','','value',''),numel(settingNames),1);
for i=1:numel(settingNames)
    settings(i).name=settingNames{i}; v=cfg.(settingNames{i});
    if ischar(v), settings(i).value=v;
    elseif isscalar(v), settings(i).value=v;
    else, settings(i).value=mat2str(v); end
end
settings(end+1)=struct('name','Endpoint convention','value','State N after N-1 updates; N innovations generated, as in original script.');
settings(end+1)=struct('name','Step shifts','value','alpha shift 0; other shifts 1 times fixed total budget N1=1000000.');
settings(end+1)=struct('name','Model choice','value','User retains original squared-normal H recursion and no clipping; paper instead specifies a signed-normal recursion and clipping.');
settings(end+1)=struct('name','Paper source','value','CVaR_Optimization - 2026-09-14T231419.819.pdf, pp.23,43-45; confidence interval Eq.(12), p.8.');
settings(end+1)=struct('name','Pseudo-RMSE definition','value','CV target C_phi(theta_r); Gcv target (1-phi)*C_phi''(theta_r).');
settings(end+1)=struct('name','Reference method','value','Independent randomized Sobol stationary H; conditional analytic Y integration; exact E[H]=3.');
settings(end+1)=struct('name','Reference sample points per distribution','value',2^cfg.referenceOptions.samplesPower*cfg.referenceOptions.numScrambles);
settings(end+1)=struct('name','Reference scrambles','value',cfg.referenceOptions.numScrambles);
settings(end+1)=struct('name','Reference seed','value',cfg.referenceOptions.seed);
settings(end+1)=struct('name','Reference finite depth','value',cfg.referenceOptions.depth);
payload.settings=settings;
payload.cases=struct([]);
metricNames={'theta_mean';'theta_SD_R';'theta_relative_error';'theta_RMSE'; ...
    'CV_mean';'CV_SD_R';'CV_relative_error_original_constant';'CV_pseudo_RMSE'; ...
    'Gcv_mean';'Gcv_SD_R';'Gcv_pseudo_RMSE'; ...
    'CI_lower_mean';'CI_lower_SD_R';'CI_upper_mean';'CI_upper_SD_R'; ...
    'CI_length_mean';'CI_coverage_original_constant';'sigma_mean'; ...
    'CV_fixed_RMSE_original_constant';'CV_fixed_RMSE_independent_reference'; ...
    'CV_pseudo_RMSE_reference_SE';'Gcv_pseudo_RMSE_reference_SE'; ...
    'CV_optimum_independent_reference';'CV_optimum_reference_SE'; ...
    'CV_original_constant';'negative_raw_variance_count';'runtime_per_replication_mean_s'};
for dist=cfg.distributions
    ids=find([cases.fenbumoshi]==dist);
    theta=zeros(cfg.xunhuancishu,numel(ids)); cv=theta; Gcv=theta;
    for j=1:numel(ids)
        reps=cases(ids(j)).replications;
        theta(:,j)=[reps.theta]'; cv(:,j)=[reps.cv]'; Gcv(:,j)=[reps.Gcv]';
    end
    name=cases(ids(1)).distribution;
    cvtrue=cases(ids(1)).cvtrueOriginal;
    opts=cfg.referenceOptions;
    opts.cacheFile=fullfile(outputDir,[tag '_reference_' name '.mat']);
    opts.stationaryCacheFile=fullfile(outputDir,[tag '_stationary_H_reference.mat']);
    R=repair_correlated_rmse(theta,cv,Gcv,cfg.phi,dist,cvtrue,opts);
    results.repairs{dist}=R;
    summary=zeros(numel(metricNames),numel(ids));
    for j=1:numel(ids)
        reps=cases(ids(j)).replications;
        CI=vertcat(reps.CI); sigma=[reps.sigma]';
        runtime=[reps.elapsedSeconds]'; seeds=[reps.seed]';
        summary(:,j)=[mean(theta(:,j));std(theta(:,j),1);mean(theta(:,j))-1; ...
            sqrt(mean((theta(:,j)-1).^2));mean(cv(:,j));std(cv(:,j),1); ...
            (mean(cv(:,j))-cvtrue)/cvtrue;R.pseudoRMSE(j); ...
            mean(Gcv(:,j));std(Gcv(:,j),1);R.gradientPseudoRMSE(j); ...
            mean(CI(:,1));std(CI(:,1),1);mean(CI(:,2));std(CI(:,2),1); ...
            mean(CI(:,2)-CI(:,1));mean(CI(:,1)<=cvtrue & CI(:,2)>=cvtrue); ...
            mean(sigma);R.optimumRMSE(j);R.independentOptimumRMSE(j); ...
            R.pseudoRMSEReferenceSE(j);R.gradientPseudoRMSEReferenceSE(j); ...
            R.referenceOptimumCVaR;R.referenceOptimumCVaRSE;cvtrue; ...
            sum([reps.varianceRaw]<0);mean(runtime)];
        p=struct('distribution',name,'N',cases(ids(j)).N,'cvtrue',cvtrue, ...
            'cvtrueSE',[],'cvOptimumReference',R.referenceOptimumCVaR, ...
            'cvOptimumReferenceSE',R.referenceOptimumCVaRSE, ...
            'pseudoRMSEReferenceSE',R.pseudoRMSEReferenceSE(j), ...
            'gradientPseudoRMSEReferenceSE',R.gradientPseudoRMSEReferenceSE(j), ...
            'raw',[(1:cfg.xunhuancishu)',theta(:,j),cv(:,j),Gcv(:,j), ...
            R.referenceCVaR(:,j),R.referenceScaledGradient(:,j), ...
            R.referenceCVaRSE(:,j),R.referenceScaledGradientSE(:,j), ...
            CI,sigma,seeds,repmat(cases(ids(j)).N,cfg.xunhuancishu,1),runtime]);
        if isempty(payload.cases), payload.cases=p;
        else, payload.cases(end+1)=p; end %#ok<AGROW>
        detail=array2table(p.raw,'VariableNames',{'replication','theta','CV','Gcv', ...
            'referenceCV','referenceScaledGradient','referenceCV_SE', ...
            'referenceScaledGradient_SE','CI_LB','CI_UB','sigma','seed','iterations','runtime_seconds'});
        detail.CV_squared_pseudo_error=R.squaredErrorsPseudo(:,j);
        detail.Gcv_squared_pseudo_error=R.squaredErrorsGradient(:,j);
        writetable(detail,fullfile(outputDir,sprintf('%s_%s_N%d_paired.csv',tag,name,p.N)));
        fprintf('RESULT %s N=%d: CV pseudo-RMSE=%.9f (reference SE %.3g); Gcv pseudo-RMSE=%.9f (SE %.3g)\n', ...
            name,p.N,R.pseudoRMSE(j),R.pseudoRMSEReferenceSE(j), ...
            R.gradientPseudoRMSE(j),R.gradientPseudoRMSEReferenceSE(j));
    end
    labels=arrayfun(@(N)sprintf('N%d',N),cfg.Nvalues,'UniformOutput',false);
    T=array2table(summary,'VariableNames',labels,'RowNames',metricNames);
    writetable(T,fullfile(outputDir,[tag '_' name '_summary.csv']),'WriteRowNames',true);
    results.([name '_summary'])=T;
end
results.metricNames=metricNames;
results.payload=payload;
json=jsonencode(payload,'PrettyPrint',true);
fid=fopen(fullfile(outputDir,'table_payload.json'),'w','n','UTF-8');
assert(fid~=-1,'Cannot write table payload.');
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',json);
save(fullfile(outputDir,[tag '_results.mat']),'results','cfg','cases','-v7');
end
