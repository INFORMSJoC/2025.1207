function export_correlated_matlab_excel(results, outputDir)
%EXPORT_CORRELATED_MATLAB_EXCEL Write a standalone static results workbook.
% Called after FINALIZE_CORRELATED_TABLES. No Excel installation is needed.
% The three worksheets contain the same numerical output as the CSV/MAT
% files. Existing workbooks are replaced only after all sheets are written.

assert(isstruct(results) && isfield(results,'payload'), ...
    'CVaR:ExcelResults','Expected results returned by finalize_correlated_tables.');
assert(isfield(results,'exponential_summary') && isfield(results,'normal_summary'), ...
    'CVaR:ExcelCases','Both exponential and normal summary tables are required.');
if ~isfolder(outputDir), mkdir(outputDir); end
outputPath=fullfile(outputDir,'CVaR_correlated_k0_2_R100_corrected.xlsx');
temporaryPath=[tempname(outputDir) '.xlsx'];
cleanup=onCleanup(@() removeTemporary(temporaryPath)); %#ok<NASGU>

% Summary: the two distributions occupy separate, labelled row blocks.
tables={results.exponential_summary,results.normal_summary};
titles={'Exponential Y ~ Exp(1)','Normal Y ~ N(0,1)'};
columnCount=width(tables{1})+1;
summary=cell(0,columnCount);
for i=1:numel(tables)
    T=tables{i};
    assert(width(T)+1==columnCount, 'CVaR:ExcelShape', ...
        'The two summary tables must have the same number of budget columns.');
    block=cell(height(T)+3,columnCount);
    block{1,1}=titles{i};
    block(2,:)=[{'Metric'},T.Properties.VariableNames];
    block(3:height(T)+2,1)=T.Properties.RowNames;
    block(3:height(T)+2,2:end)=num2cell(table2array(T));
    summary=[summary;block]; %#ok<AGROW>
end
writecell(summary,temporaryPath,'Sheet','Summary','Range','A1','UseExcel',false);

% Preserve row pairing: the 14 raw columns come directly from one case.
rawHeaders={'replication','theta','CV','Gcv','referenceCV', ...
    'referenceScaledGradient','referenceCV_SE','referenceScaledGradient_SE', ...
    'CI_LB','CI_UB','sigma','seed','iterations','runtime_seconds'};
errorHeaders={'CV_squared_pseudo_error','Gcv_squared_pseudo_error', ...
    'CV_fixed_squared_error_original_constant', ...
    'CV_fixed_squared_error_independent_reference'};
headers=[{'distribution','N'},rawHeaders,errorHeaders];
cases=results.payload.cases;
rowCount=sum(arrayfun(@(p)size(p.raw,1),cases));
replications=cell(rowCount+1,numel(headers));
replications(1,:)=headers;
cursor=2;
for i=1:numel(cases)
    p=cases(i);
    assert(size(p.raw,2)==numel(rawHeaders), 'CVaR:ExcelRawShape', ...
        'Each case must have exactly 14 raw-data columns.');
    count=size(p.raw,1);
    rows=cursor:cursor+count-1;
    replications(rows,1)=repmat({p.distribution},count,1);
    replications(rows,2)=num2cell(repmat(p.N,count,1));
    replications(rows,3:16)=num2cell(p.raw);
    cv=p.raw(:,3); Gcv=p.raw(:,4);
    referenceCV=p.raw(:,5); referenceGcv=p.raw(:,6);
    errors=[(cv-referenceCV).^2,(Gcv-referenceGcv).^2, ...
        (cv-p.cvtrue).^2,(cv-p.cvOptimumReference).^2];
    replications(rows,17:20)=num2cell(errors);
    cursor=cursor+count;
end
writecell(replications,temporaryPath,'Sheet','Replications','Range','A1','UseExcel',false);

% Settings values are already serialized by the finalizer where necessary.
sourceSettings=results.payload.settings;
settings=cell(numel(sourceSettings)+2,2);
settings(1,:)={'Setting','Value'};
for i=1:numel(sourceSettings)
    settings{i+1,1}=sourceSettings(i).name;
    settings{i+1,2}=sourceSettings(i).value;
end
settings(end,:)={'Workbook export', ...
    'MATLAB static values; CV and Gcv errors preserve per-replication theta pairing.'};
writecell(settings,temporaryPath,'Sheet','Settings','Range','A1','UseExcel',false);

[ok,message]=movefile(temporaryPath,outputPath,'f');
assert(ok,'CVaR:ExcelSave','Cannot replace the output workbook: %s',message);
fprintf('Excel workbook saved: %s\n',outputPath);
end

function removeTemporary(path)
% The name was generated by tempname solely for this export call.
if isfile(path), delete(path); end
end
